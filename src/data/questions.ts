// Local GIF asset helper that resolves cleanly in all deployment environments
const getGif = (filename: string): string => {
  const base = import.meta.env.BASE_URL || './';
  const cleanBase = base.endsWith('/') ? base : `${base}/`;
  return `${cleanBase}gifs/${filename}`;
};

